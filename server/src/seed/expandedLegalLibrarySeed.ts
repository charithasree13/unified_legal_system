export async function seedExpandedLegalLibrary() {
  try {
    console.log('📖 Seeding Expanded Judgments & Bare Acts Legal Library...');
    
    // Seed Judgements
    for (const item of EXPANDED_JUDGEMENTS_SEED) {
      const normCourt = String(item.court || '').toLowerCase().trim().replace(/^the\s+/i, '').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
      const normCaseNo = String(item.caseNumber || '').toLowerCase().trim().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
      const normCit = String(item.neutralCitation || '').toLowerCase().trim().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
      const normYr = String(item.year || '').trim();
      const canonicalKey = `${normCourt}|${normCaseNo || 'nocaseno'}|${normCit || normYr}`;

      const seedRecord = { ...item, canonicalKey };
      const existing = await Judgement.findOne({
        $or: [
          { _id: seedRecord._id },
          { canonicalKey },
          { title: seedRecord.title, court: seedRecord.court }
        ]
      });
      if (!existing) {
        await Judgement.create(seedRecord);
      }
    }

    // Seed Laws / Bare Acts
    for (const act of EXPANDED_LAWS_SEED) {
      const mainTitle = (act.actName || act.title || '').trim();
      const normName = String(mainTitle).toLowerCase().trim().replace(/^the\s+/i, '').replace(/\s*\([^)]*\)/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
      const normNo = String(act.actNumber || '').toLowerCase().trim().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
      const normYr = String(act.year || '').trim();
      const normJur = String(act.jurisdiction || 'central').toLowerCase().trim().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
      const canonicalKey = `${normName}|${normNo || 'nono'}|${normYr}|${normJur}`;

      const seedRecord = { ...act, canonicalKey };
      const existing = await Law.findOne({
        $or: [
          { _id: seedRecord._id },
          { canonicalKey },
          { title: seedRecord.title }
        ]
      });
      if (!existing) {
        await Law.create(seedRecord);
      }
    }

    console.log('✅ Expanded Legal Library seeded successfully!');
  } catch (err: any) {
    console.error('❌ Error seeding expanded legal library:', err?.message || err);
  }
}
